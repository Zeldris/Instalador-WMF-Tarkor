#!/usr/bin/env python3
"""Blind pairwise quality bench for step 5 of `scout-updates`: compares AI models on the project's own cases.
Standard library only. Generalised from the World-Maker-Fantasy bench.

Usage:
  quality_bench.py generate <cases.jsonl> --model M --output <outputs.jsonl> [--url U] [--api ollama|openai]
  quality_bench.py pairs <outputs.jsonl> <outputs.jsonl> [...] --cases <cases.jsonl> --output <pairs.jsonl> --key <key.json> [--seed N]
  quality_bench.py judge <pairs.jsonl> --judge M --rubric <rubric.md> --output <verdicts.jsonl> [--url U] [--api ...]
  quality_bench.py summary <pairs.jsonl> <key.json> <verdicts.jsonl> [--json] [--detail]

Cases: one line each, {"id", "system"?, "prompt", "context"?, "options"?: {"temperature", "num_ctx", "max_tokens",
"format"}}; `format` is the JSON Schema of structured calls. With Ollama, `think: false` is always sent. `context` is
what the judge sees (e.g. the user's action); without it, the last 1500 characters of the prompt.
generate: one line per case, {"case", "model", "output", "ms"} or {"case", "model", "error"}.
pairs: per case and per pair of models, two blind pairs (A as X and B as X), shuffled; model names appear only in the
key file. The key never goes to the judge.
judge: the judge answers {"winner": "X"|"Y"|"tie", "reason"}; a pair whose call fails gets an "error" and is left out
of the summary. To judge with an agent instead of a model server, the agent writes verdicts.jsonl by hand in that
format, with {"pair"}, without opening the key.
summary: per model, wins (a tie = 0.5) and rate; consistency = % of cases whose winner does not change when the pair is
flipped (one that changes counts as a tie); position bias = % of times X wins. With --detail, also head to head,
points per case and the reasons of the pairs each model loses (for the typical failures of the report). A rate over few
cases is an indication, not a proof: the summary prints how many pairs it rests on.
"""
import argparse
import itertools
import json
import random
import sys
import time
import urllib.request

OLLAMA_URL = 'http://localhost:11434'
CONTEXT_MAX = 1500


def read_jsonl(path):
    try:
        with open(path, encoding='utf-8') as f:
            return [json.loads(line) for line in f if line.strip()]
    except (OSError, ValueError) as e:
        sys.exit('Cannot read %s as JSON lines (%s); check the path and that each line is a JSON object' % (path, e))


def write_jsonl(path, rows):
    with open(path, 'w', encoding='utf-8') as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')


def call_http(url, api, model, system, prompt, options, json_format=False, timeout=600):
    """Text generated by the engine. api: 'ollama' (/api/generate) or 'openai' (/v1/chat/completions)."""
    options = options or {}
    if api == 'ollama':
        # think: false: without it, reasoning models write their reasoning before the answer
        body = {'model': model, 'prompt': prompt, 'stream': False, 'think': False, 'options': {}}
        if system:
            body['system'] = system
        for k in ('temperature', 'num_ctx'):
            if k in options:
                body['options'][k] = options[k]
        if 'max_tokens' in options:
            body['options']['num_predict'] = options['max_tokens']
        if json_format:
            body['format'] = 'json'
        elif 'format' in options:
            body['format'] = options['format']
        target = url.rstrip('/') + '/api/generate'
    else:
        messages = ([{'role': 'system', 'content': system}] if system else []) + [{'role': 'user', 'content': prompt}]
        body = {'model': model, 'messages': messages}
        for k in ('temperature', 'max_tokens'):
            if k in options:
                body[k] = options[k]
        if json_format:
            body['response_format'] = {'type': 'json_object'}
        elif 'format' in options:
            body['response_format'] = {'type': 'json_schema', 'json_schema': {'name': 'output', 'schema': options['format']}}
        target = url.rstrip('/') + '/v1/chat/completions'
    req = urllib.request.Request(target, json.dumps(body).encode(), {'Content-Type': 'application/json'})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        data = json.load(r)
    return data['response'] if api == 'ollama' else data['choices'][0]['message']['content']


def generate(cases, model, call):
    rows = []
    for c in cases:
        start = time.monotonic()
        try:
            output = call(model, c.get('system'), c['prompt'], c.get('options'))
            rows.append({'case': c['id'], 'model': model, 'output': output.strip(),
                         'ms': round((time.monotonic() - start) * 1000)})
        except Exception as e:  # one failed case does not bring the batch down
            rows.append({'case': c['id'], 'model': model, 'error': str(e)})
        print('%s %s %s' % (model, c['id'], 'error' if 'error' in rows[-1] else '%d ms' % rows[-1]['ms']),
              file=sys.stderr)
    return rows


def context(case):
    return case.get('context') or case['prompt'][-CONTEXT_MAX:]


def pairs(batches, cases, seed=0):
    """batches: lists of outputs, one per model. Returns (pairs, key)."""
    by_model = {}
    for batch in batches:
        for f in batch:
            if 'output' in f:
                by_model.setdefault(f['model'], {})[f['case']] = f['output']
    ctx = {c['id']: context(c) for c in cases}
    raw = []
    for a, b in itertools.combinations(sorted(by_model), 2):
        for case in sorted(set(by_model[a]) & set(by_model[b]) & set(ctx)):
            for x, y in ((a, b), (b, a)):
                raw.append((case, x, y))
    random.Random(seed).shuffle(raw)
    out, key = [], {}
    for i, (case, x, y) in enumerate(raw, 1):
        pair = 'p%03d' % i
        out.append({'pair': pair, 'case': case, 'context': ctx[case], 'X': by_model[x][case], 'Y': by_model[y][case]})
        key[pair] = {'X': x, 'Y': y}
    return out, key


JUDGE_PROMPT = """Compare two answers to the same situation according to the rubric. Ignore which one comes first, and
the length unless the rubric asks for it. Answer only with JSON: {{"winner": "X" | "Y" | "tie", "reason": "<one sentence>"}}.

Rubric:
{rubric}

Situation:
{context}

Answer X:
{x}

Answer Y:
{y}
"""


def judge(pair_list, judge_model, rubric, call):
    verdicts = []
    for p in pair_list:
        try:
            text = call(judge_model, None, JUDGE_PROMPT.format(rubric=rubric, context=p['context'], x=p['X'], y=p['Y']),
                        {'temperature': 0}, True)
        except Exception as e:  # a failed pair does not throw away the verdicts already obtained
            verdicts.append({'pair': p['pair'], 'error': str(e)})
            continue
        try:
            v = json.loads(text)
        except ValueError:
            v = {}
        v = v if isinstance(v, dict) else {}
        winner = v.get('winner') if v.get('winner') in ('X', 'Y', 'tie') else None
        verdicts.append({'pair': p['pair'], 'winner': winner or 'tie', 'reason': v.get('reason', ''),
                         **({} if winner else {'warning': 'unreadable judge answer: %s' % text[:200]})})
    return verdicts


def summary(pair_list, key, verdicts):
    case_of = {p['pair']: p['case'] for p in pair_list}
    by_round = {}  # (case, pair of models) -> [winning model, or None for a tie]
    x_wins = judged = 0
    losses = {}  # model -> pairs it loses, with the judge's reason
    seen = {}  # pair -> accepted rounds, to count every pair once
    for v in verdicts:
        pair = v['pair']
        if pair not in key or 'error' in v:
            continue
        if pair not in case_of:
            sys.exit('Pair %s is in the key but not in the pairs file; they come from different runs. Regenerate both '
                     'with the same seed: python3 quality_bench.py pairs ... --seed <n> --key <key.json>' % pair)
        seen[pair] = seen.get(pair, 0) + 1
        if seen[pair] > 1:
            continue  # the same pair judged again (verdicts appended twice): counted once, reported in `repeated`
        judged += 1
        w = v.get('winner')  # a hand-written verdict without winner counts as a tie, like an unreadable one
        x_wins += w == 'X'
        models = tuple(sorted(key[pair].values()))
        by_round.setdefault((case_of[pair], models), []).append(key[pair][w] if w in ('X', 'Y') else None)
        if w in ('X', 'Y'):
            loser = key[pair]['Y' if w == 'X' else 'X']
            losses.setdefault(loser, []).append({'case': case_of[pair], 'against': key[pair][w],
                                                 'reason': v.get('reason', '')})
    points, played = {}, {}
    head, per_case = {}, {}
    consistent = complete = 0
    repeated = sum(1 for n in seen.values() if n > 1)  # pairs judged more than once: only the first verdict counts
    for (case, models), winners in by_round.items():
        if len(winners) == 2:
            complete += 1
            if winners[0] == winners[1]:
                consistent += 1
            else:
                winners = [None, None]  # it changes when flipped: a tie
        for w in winners:
            for m in models:
                played[m] = played.get(m, 0) + 1
                score = 1 if w == m else 0.5 if w is None else 0
                points[m] = points.get(m, 0) + score
                other = models[1] if m == models[0] else models[0]
                c = head.setdefault(m, {}).setdefault(other, [0, 0])
                c[0] += score
                c[1] += 1
                per_case.setdefault(case, {})[m] = per_case.get(case, {}).get(m, 0) + score
    return {
        'models': {m: {'points': points[m], 'played': played[m], 'rate': round(points[m] / played[m], 3)}
                   for m in sorted(played, key=lambda m: -points[m] / played[m])},
        'consistency': round(consistent / complete, 3) if complete else None,
        'x_bias': round(x_wins / judged, 3) if judged else None,
        'judged': judged, 'unjudged': len(pair_list) - judged, 'repeated': repeated,
        'head_to_head': {m: {o: round(p / n, 3) for o, (p, n) in sorted(d.items())} for m, d in head.items()},
        'per_case': {c: per_case[c] for c in sorted(per_case)},
        'losses': {m: sorted(d, key=lambda x: x['case']) for m, d in losses.items()},
    }


def print_detail(res):
    models = list(res['models'])
    print('\nhead to head (rate of the row against the column):')
    print('  %-28s ' % '' + ' '.join('%10s' % m[:10] for m in models))
    for m in models:
        row = res['head_to_head'].get(m, {})
        print('  %-28s ' % m[:28] + ' '.join('%10s' % (row[o] if o in row else '-') for o in models))
    print('\npoints per case:')
    for case, d in res['per_case'].items():
        print('  %-16s ' % case + ' '.join('%10s' % ('%g' % d[m] if m in d else '-') for m in models))
    for m in models:
        print('\n%s loses:' % m)
        for x in res['losses'].get(m, []):
            print('  %s against %s: %s' % (x['case'], x['against'], x['reason']))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    sub = ap.add_subparsers(dest='command', required=True)
    g = sub.add_parser('generate')
    g.add_argument('cases')
    g.add_argument('--model', required=True)
    g.add_argument('--output', required=True)
    p = sub.add_parser('pairs')
    p.add_argument('outputs', nargs='+')
    p.add_argument('--cases', required=True)
    p.add_argument('--output', required=True)
    p.add_argument('--key', required=True)
    p.add_argument('--seed', type=int, default=0)
    j = sub.add_parser('judge')
    j.add_argument('pairs')
    j.add_argument('--judge', required=True)
    j.add_argument('--rubric', required=True)
    j.add_argument('--output', required=True)
    for s in (g, j):
        s.add_argument('--url', default=OLLAMA_URL)
        s.add_argument('--api', choices=('ollama', 'openai'), default='ollama')
    r = sub.add_parser('summary')
    r.add_argument('pairs')
    r.add_argument('key')
    r.add_argument('verdicts')
    r.add_argument('--json', action='store_true')
    r.add_argument('--detail', action='store_true')
    a = ap.parse_args(argv)

    if a.command in ('generate', 'judge'):
        def call(model, system, prompt, options, json_format=False):
            return call_http(a.url, a.api, model, system, prompt, options, json_format)
    if a.command == 'generate':
        write_jsonl(a.output, generate(read_jsonl(a.cases), a.model, call))
    elif a.command == 'pairs':
        pair_list, key = pairs([read_jsonl(s) for s in a.outputs], read_jsonl(a.cases), a.seed)
        write_jsonl(a.output, pair_list)
        with open(a.key, 'w', encoding='utf-8') as f:
            json.dump(key, f, ensure_ascii=False, indent=1)
        print('%d pairs' % len(pair_list))
    elif a.command == 'judge':
        try:
            with open(a.rubric, encoding='utf-8') as f:
                rubric = f.read()
        except OSError as e:
            sys.exit('Cannot read the rubric %s (%s); write it first, a short Markdown file with the criteria' % (a.rubric, e))
        write_jsonl(a.output, judge(read_jsonl(a.pairs), a.judge, rubric, call))
    else:
        try:
            with open(a.key, encoding='utf-8') as f:
                key = json.load(f)
        except (OSError, ValueError) as e:
            sys.exit('Cannot read the key %s (%s); it is the --key file written by `pairs`' % (a.key, e))
        res = summary(read_jsonl(a.pairs), key, read_jsonl(a.verdicts))
        if a.json:
            print(json.dumps(res, ensure_ascii=False, indent=1))
        else:
            for m, d in res['models'].items():
                print('%-40s rate %.3f (%s of %d)' % (m, d['rate'], d['points'], d['played']))
            print('consistency when flipped: %s | X wins: %s | judged %d, unjudged %d'
                  % (res['consistency'], res['x_bias'], res['judged'], res['unjudged']))
            if res['repeated']:
                print('WARNING: %d repeated verdicts (pairs judged more than once): the first verdict of each '
                      'pair counts and later ones are ignored; remove the repeated lines from the verdicts file'
                      % res['repeated'])
            if a.detail:
                print_detail(res)


if __name__ == '__main__':
    main()
